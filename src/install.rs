fn source_block(integration_path: &Path) -> Vec<u8> {
    let mut block = Vec::new();
    block.extend_from_slice(START_MARKER);
    block.extend_from_slice(b"\nsource -- ");
    append_zsh_quoted(&mut block, integration_path.as_os_str());
    block.push(b'\n');
    block.extend_from_slice(END_MARKER);
    block.push(b'\n');
    block
}

fn append_zsh_quoted(output: &mut Vec<u8>, value: &OsStr) {
    output.push(b'\'');
    for byte in value.as_bytes() {
        if *byte == b'\'' {
            output.extend_from_slice(b"'\\''");
        } else {
            output.push(*byte);
        }
    }
    output.push(b'\'');
}

