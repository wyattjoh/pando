const INTEGRATION: &[u8] = br#"# Generated by pando. Do not edit.
# The dispatcher deliberately avoids a leading underscore: that prefix is the
# zsh completion-function convention, and tools that capture a shell's function
# table (Claude Code's shell snapshots, for one) drop `_name` functions wholesale
# to skip the completion system. A dropped helper would leave `pando` and
# `pd` defined but calling a command that no longer exists.
pando_dispatch() {
  local executable="$1"
  shift
  local structured=false passthrough=false expect_format=false arg
  for arg in "$@"; do
    if [[ "$expect_format" == true ]]; then
      [[ "$arg" == json ]] && structured=true
      expect_format=false
      continue
    fi
    case "$arg" in
      --output|--input-output) expect_format=true ;;
      --output=json|--input-output=json) structured=true ;;
      -h|--help|-V|--version) passthrough=true ;;
    esac
  done
  if [[ ! -o interactive ]] || [[ "$structured" == true ]] || [[ "$passthrough" == true ]]; then
    command "$executable" "$@"
  elif [[ "$1" == "switch" || "$1" == "create" || "$1" == "remove" || "$1" == "merge" ]]; then
    local destination
    destination="$(command "$executable" "$@")"
    local exit_status=$?
    if [[ -n "$destination" ]]; then
      builtin cd -- "$destination" || return $?
    fi
    return $exit_status
  else
    command "$executable" "$@"
  fi
}

pando() { pando_dispatch pando "$@"; }
pd() { pando_dispatch pd "$@"; }

# Dynamic completion for both names. The registration script is generated on
# every shell start rather than cached: clap_complete gives no stability
# guarantee between the script it emits and the completion protocol the binary
# expects, so a cached script would silently break after a binary upgrade.
# Generating it costs one process spawn, measured under 3ms.
#
# `pd` is a symlink to the same binary, so one registration serves both names.
# The generated function is named `_clap_dynamic_completer_pando`; the
# leading underscore is the completion system's own convention here, unlike the
# dispatcher above, and a dropped snapshot copy only disables completion.
pando_register_completion() {
  (( $+functions[compdef] )) || return 1
  local script
  # Captured into a variable rather than `eval "$(... )"` directly: if the
  # binary is missing from PATH the command substitution yields an empty
  # string, and `eval ""` exits 0. That would report registration as
  # successful while leaving `_clap_dynamic_completer_pando` undefined,
  # so `compdef` below would bind both names to a function that never
  # existed and the precmd retry would never re-arm.
  script="$(_PANDO_COMPLETE=zsh command pando 2>/dev/null)" || return 1
  [[ -n "$script" ]] || return 1
  eval "$script"
  compdef _clap_dynamic_completer_pando pd
  return 0
}

if [[ -o interactive ]]; then
  if ! pando_register_completion; then
    # `compinit` has not run yet, so retry once after startup finishes.
    pando_deferred_completion() {
      pando_register_completion
      add-zsh-hook -d precmd pando_deferred_completion
      unfunction pando_deferred_completion
    }
    autoload -Uz add-zsh-hook && add-zsh-hook precmd pando_deferred_completion
  fi
fi
"#;

#[derive(Clone, Debug, Default, Deserialize, JsonSchema, Serialize)]
#[serde(deny_unknown_fields)]
pub struct InstallInput {
    #[serde(default)]
    pub dry_run: bool,
}

#[derive(Clone, Debug, JsonSchema, Serialize)]
pub struct InstallTarget {
    pub path: BytePath,
    pub would_change: bool,
}

/// Deterministic filesystem changes shared by installation adapters.
#[derive(Clone, Debug, JsonSchema, Serialize)]
pub struct InstallPlan {
    pub changed: bool,
    pub configuration: InstallTarget,
    pub integration: InstallTarget,
    pub startup: InstallTarget,
    #[serde(skip)]
    config_path: PathBuf,
    #[serde(skip)]
    integration_path: PathBuf,
    #[serde(skip)]
    startup_path: PathBuf,
    #[serde(skip)]
    desired_config: Vec<u8>,
    #[serde(skip)]
    desired_startup: Vec<u8>,
}

#[derive(Debug, JsonSchema, Serialize)]
#[serde(tag = "outcome", rename_all = "snake_case")]
pub enum InstallResult {
    DryRun { plan: InstallPlan },
    AlreadyCurrent { plan: InstallPlan },
    Installed { plan: InstallPlan },
}

#[derive(Debug)]
pub struct InstallFailure {
    code: &'static str,
    message: String,
}

impl From<InstallFailure> for ErrorBody {
    fn from(failure: InstallFailure) -> Self {
        Self {
            code: failure.code.into(),
            message: failure.message,
        }
    }
}

/// Command-owned result consumed by the human and JSON adapters.
#[derive(Debug)]
pub struct InstallOutcome {
    pub result: std::result::Result<InstallResult, InstallFailure>,
    pub effects: Vec<Effect>,
    pub recovery: Vec<RecoveryAction<protocol::EmptyInput>>,
}

/// Builds the deterministic installation plan.
///
/// # Errors
/// Returns an error when paths or existing installation files cannot be read.
pub fn plan() -> Result<InstallPlan> {
    let config_path = config_home()?.join("pando/config.yaml");
    let integration_path = config_home()?.join("pando/pando.zsh");
    let startup_path = zshrc_path()?;
    let source_block = source_block(&integration_path);
    let existing_config = read_optional(&config_path)?;
    let existing_integration = read_optional(&integration_path)?;
    let existing_startup = read_optional(&startup_path)?;
    let desired_config = update_config_scaffold(&existing_config)?;
    let desired_startup = update_source_block(&existing_startup, &source_block)?;
    let configuration_changed = existing_config != desired_config;
    let integration_changed = existing_integration != INTEGRATION;
    let startup_changed = existing_startup != desired_startup;
    Ok(InstallPlan {
        changed: configuration_changed || integration_changed || startup_changed,
        configuration: InstallTarget {
            path: BytePath::path(&config_path),
            would_change: configuration_changed,
        },
        integration: InstallTarget {
            path: BytePath::path(&integration_path),
            would_change: integration_changed,
        },
        startup: InstallTarget {
            path: BytePath::path(&startup_path),
            would_change: startup_changed,
        },
        config_path,
        integration_path,
        startup_path,
        desired_config,
        desired_startup,
    })
}

fn effects(plan: &InstallPlan, attempted: bool) -> Vec<Effect> {
    [
        ("configuration", &plan.configuration),
        ("integration", &plan.integration),
        ("startup", &plan.startup),
    ]
    .into_iter()
    .filter(|(_, target)| target.would_change)
    .map(|(role, target)| Effect {
        action: "file.write".into(),
        attempted,
        completed: attempted,
        details: Some(serde_json::json!({"target":target.path,"role":role})),
    })
    .collect()
}

/// Returns the typed non-mutating outcome for structured installation.
///
/// # Errors
/// Returns an error when the installation plan cannot be inspected.
pub fn inspect(input: &InstallInput) -> Result<InstallOutcome> {
    let plan = plan()?;
    if !plan.changed {
        return Ok(InstallOutcome {
            result: Ok(InstallResult::AlreadyCurrent { plan }),
            effects: Vec::new(),
            recovery: Vec::new(),
        });
    }
    let planned_effects = effects(&plan, false);
    if input.dry_run {
        return Ok(InstallOutcome {
            result: Ok(InstallResult::DryRun { plan }),
            effects: planned_effects,
            recovery: Vec::new(),
        });
    }
    Ok(InstallOutcome {
        result: Err(InstallFailure {
            code: "install.approval_required",
            message: "installation requires a manual human invocation".into(),
        }),
        effects: planned_effects,
        recovery: vec![RecoveryAction {
            action: "install.approve".into(),
            description: "Review and approve installation interactively".into(),
            mutation: MutationClass::Filesystem,
            requires_human_approval: true,
            invocation: RecoveryInvocation {
                argv: vec!["pando".into(), "install".into()],
                stdin: None,
                working_directory: None,
            },
        }],
    })
}

/// Renders the installation plan without writing or prompting.
///
/// # Errors
/// Returns an error when paths or existing installation files cannot be read or rendered.
pub fn preview() -> Result<()> {
    let plan = plan()?;
    ui::info(ui::heading_style().apply_to("Planned zsh integration changes:"))?;
    for (path, changed) in [
        (&plan.integration_path, plan.integration.would_change),
        (&plan.startup_path, plan.startup.would_change),
    ] {
        let state = if changed {
            "would update"
        } else {
            "already current"
        };
        ui::step(format!(
            "{state}: {}",
            ui::worktree_data_style().apply_to(path.display())
        ))?;
    }
    ui::finish(ui::success_style().apply_to("Installation preview complete."))
}

/// Installs or updates the managed zsh integration after confirmation.
///
/// When `guided` is true, the deterministic shell installation is followed by
/// an interactive agent selector and an LLM-guided configuration session.
///
/// # Errors
///
/// Returns an error when environment paths cannot be resolved, existing files
/// cannot be inspected, confirmation cannot be read, a planned write fails, or
/// the selected agent cannot complete its session.
pub fn run(guided: bool) -> Result<()> {
    let plan = plan()?;
    let shell_changed = plan.changed;

    if shell_changed {
        ui::ensure_interactive("Pando installation requires confirmation")?;
        ui::info(ui::heading_style().apply_to("Planned Pando installation changes:"))?;
        for (verb, path, changed) in [
            ("write", &plan.config_path, plan.configuration.would_change),
            (
                "write",
                &plan.integration_path,
                plan.integration.would_change,
            ),
            ("update", &plan.startup_path, plan.startup.would_change),
        ] {
            if changed {
                ui::step(format!(
                    "{verb} {}",
                    ui::worktree_data_style().apply_to(path.display())
                ))?;
            }
        }

        let confirmed = ui::prompt_result(
            confirm("Apply these changes?")
                .initial_value(false)
                .interact(),
            "installation cancelled",
            "failed to read installation confirmation",
        )?;
        if !confirmed {
            return Err(ui::declined_noop(
                "Installation declined; no files were changed.",
                "Zsh integration was not installed.",
            ));
        }

        let outcome = apply(&plan);
        if let Err(failure) = outcome.result {
            bail!(failure.message);
        }
        ui::success("Installed zsh integration.")?;
        ui::info(format!(
            "Restart zsh or run: source {}",
            ui::worktree_data_style().apply_to(plan.startup_path.display())
        ))?;
    } else {
        ui::info("The Pando shell integration is already current.")?;
    }

    if guided {
        return run_guided_configuration(&plan.config_path);
    }

    let completion = if shell_changed {
        "Zsh integration installed."
    } else {
        "Pando installation is already current."
    };
    ui::finish(ui::success_style().apply_to(completion))
}

fn apply(plan: &InstallPlan) -> InstallOutcome {
    let mut effects = effects(plan, false);
    let writes = [
        (
            plan.configuration.would_change,
            &plan.config_path,
            plan.desired_config.as_slice(),
            "update",
        ),
        (
            plan.integration.would_change,
            &plan.integration_path,
            INTEGRATION,
            "write",
        ),
        (
            plan.startup.would_change,
            &plan.startup_path,
            plan.desired_startup.as_slice(),
            "update",
        ),
    ];
    let mut effect_index = 0;
    for (changed, path, desired, verb) in writes {
        if !changed {
            continue;
        }
        effects[effect_index].attempted = true;
        if let Err(error) = write_atomic(path, desired) {
            return InstallOutcome {
                result: Err(InstallFailure {
                    code: "install.write_failed",
                    message: format!("failed to {verb} {}: {error:#}", path.display()),
                }),
                effects,
                recovery: Vec::new(),
            };
        }
        effects[effect_index].completed = true;
        effect_index += 1;
    }
    InstallOutcome {
        result: Ok(InstallResult::Installed { plan: plan.clone() }),
        effects,
        recovery: Vec::new(),
    }
}

#[derive(Clone, Copy)]
struct KnownAgent {
    executable: &'static str,
    label: &'static str,
    command: &'static str,
}

const KNOWN_AGENTS: [KnownAgent; 4] = [
    KnownAgent {
        executable: "pi",
        label: "Pi",
        command: "pi",
    },
    KnownAgent {
        executable: "claude",
        label: "Claude Code",
        command: "claude",
    },
    KnownAgent {
        executable: "codex",
        label: "Codex",
        command: "codex",
    },
    KnownAgent {
        executable: "gemini",
        label: "Gemini CLI",
        command: "gemini",
    },
];

struct AgentChoice {
    label: String,
    hint: &'static str,
    command: String,
}

fn run_guided_configuration(config_path: &Path) -> Result<()> {
    ui::ensure_interactive("guided Pando configuration requires an interactive terminal")?;
    let saved_command = config::load_install_command(config_path)?;
    let choices = agent_choices(saved_command.as_deref());
    let mut selector = select("Choose your connected LLM agent")
        .initial_value(0)
        .max_rows(6);
    for (index, choice) in choices.iter().enumerate() {
        selector = selector.item(index, &choice.label, choice.hint);
    }
    let selected = ui::prompt_result(
        selector.interact(),
        "agent selection cancelled",
        "failed to read the agent selection",
    )?;
    let default_command = &choices[selected].command;
    let mut command_prompt = input("Command to launch the agent").validate(|value: &String| {
        validate_agent_command(value).map_err(|error| error.to_string())
    });
    if !default_command.is_empty() {
        command_prompt = command_prompt.default_input(default_command);
    }
    let command: String = ui::prompt_result(
        command_prompt.interact(),
        "agent command entry cancelled",
        "failed to read the agent command",
    )?;
    let command = command.trim().to_owned();

    let confirmed = ui::prompt_result(
        confirm("Save this command and start guided configuration?")
            .initial_value(true)
            .interact(),
        "guided configuration cancelled",
        "failed to read guided configuration confirmation",
    )?;
    if !confirmed {
        return Err(ui::declined_noop(
            "Guided configuration declined; the agent command was not saved.",
            "Zsh integration installed without guided configuration.",
        ));
    }

    let existing = read_optional(config_path)?;
    let desired = persist_install_command(&existing, saved_command.as_deref(), &command)?;
    if existing != desired {
        write_atomic(config_path, &desired)
            .with_context(|| format!("failed to update {}", config_path.display()))?;
    }
    ui::step(format!(
        "saved guided installer command in {}",
        ui::worktree_data_style().apply_to(config_path.display())
    ))?;

    let cwd = env::current_dir().context("failed to resolve the guided session directory")?;
    let prompt = guided_prompt(config_path, &cwd, &command);
    ui::info(format!(
        "Launching {} for guided configuration...",
        ui::worktree_data_style().apply_to(&command)
    ))?;
    run_agent(&command, &prompt, &cwd)?;
    ui::success("Guided configuration session completed.")?;
    ui::finish(ui::success_style().apply_to("Pando installation and configuration complete."))
}

fn agent_choices(saved_command: Option<&str>) -> Vec<AgentChoice> {
    let mut choices = Vec::new();
    if let Some(saved) = saved_command {
        let label = KNOWN_AGENTS
            .iter()
            .find(|agent| agent.command == saved)
            .map_or_else(
                || "Saved command".to_owned(),
                |agent| format!("{} (saved)", agent.label),
            );
        choices.push(AgentChoice {
            label,
            hint: "from global config",
            command: saved.to_owned(),
        });
    }
    for agent in KNOWN_AGENTS {
        if saved_command == Some(agent.command) || !executable_on_path(agent.executable) {
            continue;
        }
        choices.push(AgentChoice {
            label: agent.label.to_owned(),
            hint: "detected on PATH",
            command: agent.command.to_owned(),
        });
    }
    choices.push(AgentChoice {
        label: "Custom command".to_owned(),
        hint: "enter another agent CLI",
        command: String::new(),
    });
    choices
}

fn executable_on_path(name: &str) -> bool {
    env::var_os("PATH").is_some_and(|path| {
        env::split_paths(&path).any(|directory| {
            fs::metadata(directory.join(name)).is_ok_and(|metadata| {
                metadata.is_file() && metadata.permissions().mode() & 0o111 != 0
            })
        })
    })
}

fn guided_prompt(config_path: &Path, cwd: &Path, command: &str) -> String {
    format!(
        "You are guiding the user through a complete Pando installation and configuration. \
The deterministic zsh integration is already installed. Continue as an interactive conversation: \
inspect the local environment, explain each relevant choice, ask the user for preferences, and use \
your file tools to update the global YAML config at {config_path}. Preserve both Pando-managed marker \
blocks exactly, including install.command, which must remain {command:?}. Configure the full useful \
global surface as appropriate: worktrees.root, worktrees.default-sort, worktrees.base, \
worktrees.target-branch, commit.generation, merge.squash and merge.generation, pr.provider, \
pr.generation, and pr.pull-request-template. Values are strict YAML. default-sort accepts git, branch, \
last-commit-at, or path; base accepts head or fresh; pr.provider accepts auto, github, or tea. Global \
configuration cannot define hooks. If the current directory {cwd} is in a Git repository, you may \
also explain the committed .pando.yaml and ignored .pando.local.yaml layers, but edit them only after \
explicit user approval. Never overwrite unrelated settings or comments. Validate the resulting YAML \
and finish by summarizing what you changed and any commands the user still needs to run.",
        config_path = config_path.display(),
        cwd = cwd.display(),
    )
}

fn run_agent(command: &str, prompt: &str, cwd: &Path) -> Result<()> {
    let agent_stdout = OpenOptions::new()
        .write(true)
        .open("/dev/stderr")
        .context("failed to open stderr for the guided agent")?;
    let invocation = agent_invocation(command, prompt)?;
    let status = Command::new("/bin/sh")
        .args(["-c", &invocation])
        .current_dir(cwd)
        .stdin(Stdio::inherit())
        .stdout(Stdio::from(agent_stdout))
        .stderr(Stdio::inherit())
        .status()
        .context("failed to start the guided configuration agent")?;
    if status.success() {
        return Ok(());
    }
    if status
        .signal()
        .is_some_and(|signal| matches!(signal, 2 | 3 | 15))
    {
        bail!("guided configuration agent was interrupted");
    }
    bail!("guided configuration agent failed with {status}")
}

fn validate_agent_command(command: &str) -> Result<()> {
    let command = command.trim();
    if command.is_empty() {
        bail!("agent command cannot be empty");
    }
    let placeholders = command.matches("{prompt}").count();
    if placeholders > 1 {
        bail!("agent command may contain at most one {{prompt}} placeholder");
    }
    if placeholders == 0 && command.chars().any(|value| "|&;<>\n\r".contains(value)) {
        bail!(
            "commands with shell operators must place {{prompt}} where the agent should receive it"
        );
    }
    Ok(())
}

fn agent_invocation(command: &str, prompt: &str) -> Result<String> {
    validate_agent_command(command)?;
    let prompt = shell_quote(prompt);
    if command.contains("{prompt}") {
        return Ok(format!("exec {}", command.replace("{prompt}", &prompt)));
    }
    Ok(format!("exec {command} {prompt}"))
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

#[derive(Serialize)]
struct ManagedInstallConfig<'a> {
    install: ManagedInstallCommand<'a>,
}

#[derive(Serialize)]
struct ManagedInstallCommand<'a> {
    command: &'a str,
}

fn install_command_block(command: &str) -> Result<Vec<u8>> {
    let yaml = serde_yaml::to_string(&ManagedInstallConfig {
        install: ManagedInstallCommand { command },
    })?;
    Ok([
        INSTALL_START_MARKER,
        b"\n",
        yaml.as_bytes(),
        INSTALL_END_MARKER,
        b"\n",
    ]
    .concat())
}

fn persist_install_command(
    existing: &[u8],
    saved_command: Option<&str>,
    command: &str,
) -> Result<Vec<u8>> {
    let has_managed_block = find_bytes(existing, INSTALL_START_MARKER).is_some();
    if !has_managed_block && has_top_level_install(existing)? {
        if saved_command == Some(command) {
            return Ok(existing.to_vec());
        }
        bail!(
            "install.command already exists outside Pando's managed block; update it manually or move it between the guided installer markers"
        );
    }
    update_install_command(existing, command)
}

fn has_top_level_install(existing: &[u8]) -> Result<bool> {
    if existing.is_empty() {
        return Ok(false);
    }
    let document: serde_yaml::Value = serde_yaml::from_slice(existing)
        .context("failed to inspect install.command in the global configuration")?;
    let Some(mapping) = document.as_mapping() else {
        return Ok(false);
    };
    Ok(mapping.contains_key(serde_yaml::Value::String("install".to_owned())))
}

fn update_install_command(existing: &[u8], command: &str) -> Result<Vec<u8>> {
    let has_start = find_bytes(existing, INSTALL_START_MARKER).is_some();
    let has_end = find_bytes(existing, INSTALL_END_MARKER).is_some();
    if has_start != has_end {
        bail!("config.yaml contains an incomplete pando guided installer block");
    }

    let block = install_command_block(command)?;
    let mut output = Vec::with_capacity(existing.len() + block.len() + 1);
    let mut remaining = existing;
    let mut inserted = false;
    while let Some(start) = find_bytes(remaining, INSTALL_START_MARKER) {
        output.extend_from_slice(&remaining[..start]);
        let managed = &remaining[start..];
        let Some(relative_end) = find_bytes(managed, INSTALL_END_MARKER) else {
            bail!("config.yaml contains an unterminated pando guided installer block");
        };
        let mut after = relative_end + INSTALL_END_MARKER.len();
        if managed.get(after..after + 2) == Some(b"\r\n") {
            after += 2;
        } else if managed.get(after) == Some(&b'\n') {
            after += 1;
        }
        if !inserted {
            output.extend_from_slice(&block);
            inserted = true;
        }
        remaining = &managed[after..];
    }
    output.extend_from_slice(remaining);
    if !inserted {
        if !output.is_empty() && !output.ends_with(b"\n") {
            output.push(b'\n');
        }
        output.extend_from_slice(&block);
    }
    Ok(output)
}

fn config_home() -> Result<PathBuf> {
    if let Some(path) = nonempty_var("XDG_CONFIG_HOME") {
        return Ok(PathBuf::from(path));
    }
    Ok(home()?.join(".config"))
}

fn zshrc_path() -> Result<PathBuf> {
    if let Some(path) = nonempty_var("ZDOTDIR") {
        return Ok(PathBuf::from(path).join(".zshrc"));
    }
    Ok(home()?.join(".zshrc"))
}

fn home() -> Result<PathBuf> {
    nonempty_var("HOME")
        .map(PathBuf::from)
        .context("HOME is not set; cannot choose a zsh configuration location")
}

fn nonempty_var(name: &str) -> Option<std::ffi::OsString> {
    env::var_os(name).filter(|value| !value.is_empty())
}

fn read_optional(path: &Path) -> Result<Vec<u8>> {
    match fs::read(path) {
        Ok(content) => Ok(content),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(error) => {
            Err(error).with_context(|| format!("failed to read existing file {}", path.display()))
        }
    }
}

fn update_config_scaffold(existing: &[u8]) -> Result<Vec<u8>> {
    let mut output = Vec::with_capacity(existing.len() + CONFIG_SCAFFOLD.len() + 1);
    let mut remaining = existing;
    let mut inserted = false;

    while let Some(start) = find_bytes(remaining, CONFIG_START_MARKER) {
        output.extend_from_slice(&remaining[..start]);
        let managed = &remaining[start..];
        let Some(relative_end) = find_bytes(managed, CONFIG_END_MARKER) else {
            bail!("config.yaml contains an unterminated pando configuration scaffold");
        };
        let mut after = relative_end + CONFIG_END_MARKER.len();
        if managed.get(after..after + 2) == Some(b"\r\n") {
            after += 2;
        } else if managed.get(after) == Some(&b'\n') {
            after += 1;
        }
        if !inserted {
            output.extend_from_slice(CONFIG_SCAFFOLD);
            inserted = true;
        }
        remaining = &managed[after..];
    }
    output.extend_from_slice(remaining);

    if !inserted {
        if !output.is_empty() && !output.ends_with(b"\n") {
            output.push(b'\n');
        }
        output.extend_from_slice(CONFIG_SCAFFOLD);
    }
    Ok(output)
}

fn source_block(integration_path: &Path) -> Vec<u8> {
    let mut block = Vec::new();
    block.extend_from_slice(START_MARKER);
    block.extend_from_slice(b"\nsource -- ");
    append_zsh_quoted(&mut block, integration_path.as_os_str());
    block.push(b'\n');
    block.extend_from_slice(END_MARKER);
    block.push(b'\n');
    block
}

fn append_zsh_quoted(output: &mut Vec<u8>, value: &OsStr) {
    output.push(b'\'');
    for byte in value.as_bytes() {
        if *byte == b'\'' {
            output.extend_from_slice(b"'\\''");
        } else {
            output.push(*byte);
        }
    }
    output.push(b'\'');
}

fn update_source_block(existing: &[u8], source_block: &[u8]) -> Result<Vec<u8>> {
    let mut output = Vec::with_capacity(existing.len() + source_block.len() + 1);
    let mut remaining = existing;
    let mut inserted = false;

    while let Some(start) = find_bytes(remaining, START_MARKER) {
        output.extend_from_slice(&remaining[..start]);
        let managed = &remaining[start..];
        let Some(relative_end) = find_bytes(managed, END_MARKER) else {
            bail!("{} contains an unterminated pando source block", ".zshrc");
        };
        let mut after = relative_end + END_MARKER.len();
        if managed.get(after..after + 2) == Some(b"\r\n") {
            after += 2;
        } else if managed.get(after) == Some(&b'\n') {
            after += 1;
        }
        if !inserted {
            output.extend_from_slice(source_block);
            inserted = true;
        }
        remaining = &managed[after..];
    }
    output.extend_from_slice(remaining);

    if !inserted {
        if !output.is_empty() && !output.ends_with(b"\n") {
            output.push(b'\n');
        }
        output.extend_from_slice(source_block);
    }
    Ok(output)
}

fn find_bytes(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack
        .windows(needle.len())
        .position(|window| window == needle)
}

fn write_atomic(path: &Path, content: &[u8]) -> Result<()> {
    let destination = match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => fs::canonicalize(path)
            .with_context(|| format!("refusing to replace broken symlink {}", path.display()))?,
        Ok(_) => path.to_path_buf(),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => path.to_path_buf(),
        Err(error) => {
            return Err(error)
                .with_context(|| format!("failed to inspect destination {}", path.display()));
        }
    };
    write_atomic_file(&destination, content)
}

fn write_atomic_file(path: &Path, content: &[u8]) -> Result<()> {
    let parent = path
        .parent()
        .with_context(|| format!("{} has no parent directory", path.display()))?;
    fs::create_dir_all(parent)
        .with_context(|| format!("failed to create directory {}", parent.display()))?;

    let existing_permissions = fs::metadata(path)
        .ok()
        .map(|metadata| metadata.permissions());
    for attempt in 0..100_u8 {
        let temporary = parent.join(format!(".pando.tmp.{}.{}", std::process::id(), attempt));
        let file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary);
        let mut file = match file {
            Ok(file) => file,
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(error) => return Err(error.into()),
        };
        let result = (|| -> Result<()> {
            file.write_all(content)?;
            file.sync_all()?;
            if let Some(permissions) = existing_permissions.clone() {
                file.set_permissions(permissions)?;
            }
            drop(file);
            fs::rename(&temporary, path)?;
            Ok(())
        })();
        if result.is_err() {
            let _ = fs::remove_file(&temporary);
        }
        return result;
    }
    bail!(
        "could not allocate a temporary file beside {}",
        path.display()
    )
}

#[cfg(test)]
mod tests {
    use super::{
        CONFIG_END_MARKER, CONFIG_START_MARKER, END_MARKER, INSTALL_END_MARKER,
        INSTALL_START_MARKER, START_MARKER, agent_invocation, persist_install_command,
        update_config_scaffold, update_install_command, update_source_block,
    };

    #[test]
    fn config_scaffold_is_added_and_idempotent() {
        let existing = b"worktrees:\n  default-sort: path\n";
        let updated = update_config_scaffold(existing).unwrap();
        assert!(updated.starts_with(existing));
        assert_eq!(update_config_scaffold(&updated).unwrap(), updated);
        assert_eq!(count_marker(&updated, CONFIG_START_MARKER), 1);
        assert_eq!(count_marker(&updated, CONFIG_END_MARKER), 1);
    }

    #[test]
    fn guided_installer_command_is_added_updated_and_idempotent() {
        let existing = b"worktrees:\n  root: ../worktrees\n";
        let installed = update_install_command(existing, "pi").unwrap();
        assert!(installed.starts_with(existing));
        assert!(
            installed
                .windows(b"command: pi".len())
                .any(|value| value == b"command: pi")
        );
        assert_eq!(update_install_command(&installed, "pi").unwrap(), installed);

        let updated = update_install_command(&installed, "claude --model opus").unwrap();
        assert!(
            updated
                .windows(b"command: claude --model opus".len())
                .any(|value| value == b"command: claude --model opus")
        );
        assert_eq!(count_marker(&updated, INSTALL_START_MARKER), 1);
        assert_eq!(count_marker(&updated, INSTALL_END_MARKER), 1);
    }

    #[test]
    fn unmarked_install_command_is_preserved_without_creating_duplicate_yaml() {
        let existing = b"install:\n  command: claude\nworktrees:\n  root: ../worktrees\n";
        assert_eq!(
            persist_install_command(existing, Some("claude"), "claude").unwrap(),
            existing
        );
        assert!(
            persist_install_command(existing, Some("claude"), "pi")
                .unwrap_err()
                .to_string()
                .contains("outside Pando's managed block")
        );
    }

    #[test]
    fn guided_installer_rejects_an_orphaned_end_marker() {
        let existing = [INSTALL_END_MARKER, b"\n"].concat();
        assert!(
            update_install_command(&existing, "pi")
                .unwrap_err()
                .to_string()
                .contains("incomplete pando guided installer block")
        );
    }

    #[test]
    fn shell_operators_require_an_explicit_prompt_placeholder() {
        assert!(agent_invocation("claude | tee transcript", "configure").is_err());
        assert_eq!(
            agent_invocation("claude {prompt} | tee transcript", "configure").unwrap(),
            "exec claude 'configure' | tee transcript"
        );
        assert_eq!(
            agent_invocation("claude --model opus", "configure").unwrap(),
            "exec claude --model opus 'configure'"
        );
    }

    #[test]
    fn config_scaffold_replaces_only_its_managed_block() {
        let existing = [
            b"commit:\n  generation:\n    command: custom\n".as_slice(),
            CONFIG_START_MARKER,
            b"\n# old scaffold\n".as_slice(),
            CONFIG_END_MARKER,
            b"\n".as_slice(),
        ]
        .concat();
        let updated = update_config_scaffold(&existing).unwrap();
        assert!(updated.starts_with(b"commit:\n  generation:\n    command: custom\n"));
        assert_eq!(count_marker(&updated, CONFIG_START_MARKER), 1);
        assert_eq!(count_marker(&updated, CONFIG_END_MARKER), 1);
        assert!(
            !updated
                .windows(b"# old scaffold".len())
                .any(|window| window == b"# old scaffold")
        );
    }

    fn count_marker(value: &[u8], marker: &[u8]) -> usize {
        value
            .windows(marker.len())
            .filter(|window| *window == marker)
            .count()
    }

    #[test]
    fn replacing_managed_content_preserves_unrelated_bytes() {
        let existing = [
            b"before\xff\n".as_slice(),
            START_MARKER,
            b"\nold\n".as_slice(),
            END_MARKER,
            b"\nafter\n".as_slice(),
        ]
        .concat();
        let desired = [START_MARKER, b"\nnew\n".as_slice(), END_MARKER, b"\n"].concat();
        let updated = update_source_block(&existing, &desired).unwrap();
        assert_eq!(
            updated,
            [b"before\xff\n".as_slice(), desired.as_slice(), b"after\n"].concat()
        );
    }

    #[test]
    fn duplicate_managed_blocks_are_normalized() {
        let block = [START_MARKER, b"\nold\n".as_slice(), END_MARKER, b"\n"].concat();
        let existing = [block.as_slice(), b"middle\n", block.as_slice()].concat();
        let desired = [START_MARKER, b"\nnew\n".as_slice(), END_MARKER, b"\n"].concat();
        let updated = update_source_block(&existing, &desired).unwrap();
        assert_eq!(updated, [desired.as_slice(), b"middle\n"].concat());
    }
}
