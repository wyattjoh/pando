const INTEGRATION: &[u8] = br#"# Generated by pando. Do not edit.
# The dispatcher deliberately avoids a leading underscore: that prefix is the
# zsh completion-function convention, and tools that capture a shell's function
# table (Claude Code's shell snapshots, for one) drop `_name` functions wholesale
# to skip the completion system. A dropped helper would leave `pando` and
# `pd` defined but calling a command that no longer exists.
pando_dispatch() {
  local executable="$1"
  shift
  local structured=false passthrough=false expect_format=false arg
  for arg in "$@"; do
    if [[ "$expect_format" == true ]]; then
      [[ "$arg" == json ]] && structured=true
      expect_format=false
      continue
    fi
    case "$arg" in
      --output|--input-output) expect_format=true ;;
      --output=json|--input-output=json) structured=true ;;
      -h|--help|-V|--version) passthrough=true ;;
    esac
  done
  if [[ ! -o interactive ]] || [[ "$structured" == true ]] || [[ "$passthrough" == true ]]; then
    command "$executable" "$@"
  elif [[ "$1" == "switch" || "$1" == "create" || "$1" == "remove" || "$1" == "merge" ]]; then
    local destination
    destination="$(command "$executable" "$@")"
    local exit_status=$?
    if [[ -n "$destination" ]]; then
      builtin cd -- "$destination" || return $?
    fi
    return $exit_status
  else
    command "$executable" "$@"
  fi
}

pando() { pando_dispatch pando "$@"; }
pd() { pando_dispatch pd "$@"; }

# Dynamic completion for both names. The registration script is generated on
# every shell start rather than cached: clap_complete gives no stability
# guarantee between the script it emits and the completion protocol the binary
# expects, so a cached script would silently break after a binary upgrade.
# Generating it costs one process spawn, measured under 3ms.
#
# `pd` is a symlink to the same binary, so one registration serves both names.
# The generated function is named `_clap_dynamic_completer_pando`; the
# leading underscore is the completion system's own convention here, unlike the
# dispatcher above, and a dropped snapshot copy only disables completion.
pando_register_completion() {
  (( $+functions[compdef] )) || return 1
  local script
  # Captured into a variable rather than `eval "$(... )"` directly: if the
  # binary is missing from PATH the command substitution yields an empty
  # string, and `eval ""` exits 0. That would report registration as
  # successful while leaving `_clap_dynamic_completer_pando` undefined,
  # so `compdef` below would bind both names to a function that never
  # existed and the precmd retry would never re-arm.
  script="$(_PANDO_COMPLETE=zsh command pando 2>/dev/null)" || return 1
  [[ -n "$script" ]] || return 1
  eval "$script"
  compdef _clap_dynamic_completer_pando pd
  return 0
}

if [[ -o interactive ]]; then
  if ! pando_register_completion; then
    # `compinit` has not run yet, so retry once after startup finishes.
    pando_deferred_completion() {
      pando_register_completion
      add-zsh-hook -d precmd pando_deferred_completion
      unfunction pando_deferred_completion
    }
    autoload -Uz add-zsh-hook && add-zsh-hook precmd pando_deferred_completion
  fi
fi
"#;

